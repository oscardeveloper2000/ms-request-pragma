CREATE INDEX IF NOT EXISTS idx_request_application_status_id
    ON public.request_application USING btree
    (status_id ASC NULLS LAST)
    TABLESPACE pg_default;

-- Índices adicionales recomendados
CREATE INDEX IF NOT EXISTS idx_request_application_document_number
