-- Table: public.status
-- DROP TABLE IF EXISTS public.status;
CREATE TABLE IF NOT EXISTS public.status
(
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    name character varying(100) COLLATE pg_catalog."default" NOT NULL,
    description text COLLATE pg_catalog."default",
    CONSTRAINT status_pkey PRIMARY KEY (id)
)
TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.status
    OWNER to gestor;

-- Table: public.type_loan
-- DROP TABLE IF EXISTS public.type_loan;
CREATE TABLE IF NOT EXISTS public.type_loan
(
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    name character varying(150) COLLATE pg_catalog."default" NOT NULL,
    min_amount numeric(18,2) NOT NULL,
    max_amount numeric(18,2) NOT NULL,
    interest_rate double precision NOT NULL,
    automatic_validation boolean NOT NULL DEFAULT false,
    CONSTRAINT type_loan_pkey PRIMARY KEY (id),
    CONSTRAINT chk_type_loan_amounts CHECK (min_amount >= 0::numeric AND max_amount >= 0::numeric AND max_amount >= min_amount),
    CONSTRAINT chk_type_loan_interest CHECK (interest_rate >= 0::double precision)
)
TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.type_loan
    OWNER to gestor;

-- Table: public.request_application
-- DROP TABLE IF EXISTS public.request_application;
CREATE TABLE IF NOT EXISTS public.request_application
(
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    document_number character varying(50) COLLATE pg_catalog."default" NOT NULL,
    amount numeric(18,2) NOT NULL,
    term integer NOT NULL,
    email character varying(254) COLLATE pg_catalog."default" NOT NULL,
    loan_type_id bigint NOT NULL,
    status_id bigint NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT request_application_pkey PRIMARY KEY (id),
    CONSTRAINT fk_request_application_loan_type FOREIGN KEY (loan_type_id)
        REFERENCES public.type_loan (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT fk_request_application_status FOREIGN KEY (status_id)
        REFERENCES public.status (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT chk_request_application_amount CHECK (amount >= 0::numeric),
    CONSTRAINT chk_request_application_term CHECK (term > 0)
)
TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.request_application
    OWNER to gestor;

